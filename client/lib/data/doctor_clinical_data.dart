  static List<ClinicalMedicineComparison> search(String query) {
    if (query.trim().isEmpty) return medicines;
    final lower = query.trim().toLowerCase();
    return medicines.where((m) {
      return m.cleanName.toLowerCase().contains(lower) ||
          m.altName.toLowerCase().contains(lower) ||
          m.therapeuticCategory.toLowerCase().contains(lower);
    }).toList();
  }

  static ClinicalMedicineComparison? findByName(String name) {
    final lower = name.trim().toLowerCase();
    try {
      return medicines.firstWhere(
        (m) => m.cleanName.toLowerCase() == lower,
      );
    } catch (_) {
      try {
        return medicines.firstWhere(
          (m) => m.cleanName.toLowerCase().contains(lower) ||
              lower.contains(m.cleanName.toLowerCase()),
        );
      } catch (_) {
        return null;
      }
    }
  }
